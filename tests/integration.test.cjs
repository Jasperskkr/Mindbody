const { test } = require('node:test')
const assert = require('node:assert/strict')
const { memoryStorage, createRuntime, vue } = require('./helpers.cjs')

test('flows A–F: form save → home/history/trends → reload → export → cancel/delete → clear all', async () => {
  const memory = memoryStorage()
  const downloads = []
  const overrides = { 'src/platform/export-json.ts': { async downloadJsonFile(filename, json) { downloads.push({ filename, json }) } } }
  let runtime = createRuntime(memory.uni, overrides)
  let storage = runtime.load('src/storage/daily-records.ts')
  const { getLocalDateKey } = runtime.load('src/utils/date.ts')
  const today = getLocalDateKey()
  const yesterdayDate = new Date(`${today}T12:00:00`)
  yesterdayDate.setDate(yesterdayDate.getDate() - 1)
  const yesterday = getLocalDateKey(yesterdayDate)
  let form = runtime.page('src/pages/record/index.vue')
  await form.show()
  form.state.form.mood = 4
  form.state.form.sleepHours = '0'
  form.state.form.bodyNote = 'synthetic integration fixture only'
  await vue.nextTick()
  await form.state.saveRecord()
  assert.equal(form.state.feedbackKind.value, 'success')
  let home = runtime.page('src/pages/index/index.vue')
  let history = runtime.page('src/pages/history/index.vue')
  await home.show(); await history.show()
  assert.equal(home.state.record.value.sleepHours, 0)
  assert.equal(history.state.records.value[0].date, today)
  assert.equal(history.state.trends.value.series[3].points.at(-1).value, 0)
  // 连续多天输入经过同一公共保存接口；当前 UI 仍仅允许填写当天。
  await storage.saveDailyRecord({ date: yesterday, mood: 2, energy: 1, sleepHours: 8 })
  await history.show()
  assert.deepEqual(history.state.records.value.map((record) => record.date), [today, yesterday])
  assert.equal(history.state.trends.value.series[0].average, 3)
  assert.equal(history.state.trends.value.series[3].average, 4)
  history.state.selectedDays.value = 30
  assert.equal(history.state.trends.value.series[0].points.length, 30)
  // 模拟刷新：重新创建所有页面和模块，保留同一个隔离内存存储。
  runtime = createRuntime(memory.uni, overrides)
  storage = runtime.load('src/storage/daily-records.ts')
  home = runtime.page('src/pages/index/index.vue')
  history = runtime.page('src/pages/history/index.vue')
  form = runtime.page('src/pages/record/index.vue')
  await home.show(); await history.show(); await form.show()
  assert.equal(home.state.record.value.mood, 4)
  assert.equal(history.state.records.value.length, 2)
  assert.equal(form.state.form.sleepHours, '0')
  await history.state.exportRecords()
  assert.deepEqual(JSON.parse(downloads[0].json).records, await storage.listDailyRecords())
  const beforeCancel = [...memory.data]
  history.state.requestDelete(today)
  history.state.cancelDeletion()
  assert.deepEqual([...memory.data], beforeCancel)
  history.state.requestDelete(yesterday)
  await history.state.confirmDeletion()
  assert.equal(history.state.records.value.length, 1)
  assert.equal(history.state.trends.value.series[3].count, 1)
  assert.equal(history.state.trends.value.series[3].average, 0)
  assert.equal((await storage.loadDailyRecord(today)).mood, 4)
  history.state.requestClearAll()
  await history.state.confirmDeletion()
  assert.equal(history.state.records.value.length, 1)
  await history.state.confirmDeletion()
  await home.show(); await form.show()
  assert.equal(home.state.record.value, null)
  assert.equal(home.state.overviewStatus.value, '尚未记录')
  assert.deepEqual(history.state.records.value, [])
  assert.equal(history.state.trends.value.recordCount, 0)
  assert.ok(history.state.trends.value.series.every((series) => series.average === null && series.count === 0))
  assert.equal(form.state.form.sleepHours, '')
})
